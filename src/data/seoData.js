/**
 * Builds the complete Schema.org JSON-LD payload for a service page
 */
export function buildServiceJsonLd(serviceKey) {
  const data = SEO_DATA[serviceKey];
  if (!data) return null;

  const organization = {
    "@type": "LocalBusiness",
    "@id": `${BASE_URL}/#organization`,
    "name": BRAND.name,
    "legalName": "Yellow Springs Event Management & Production UAE",
    "url": BASE_URL,
    "logo": `${BASE_URL}${BRAND.logo}`,
    "image": data.ogImage,
    "description": BRAND.tagline + " - 15+ years of bespoke event production in Dubai and the UAE.",
    "telephone": BRAND.phone,
    "email": BRAND.email,
    "priceRange": "$$$$",
    "address": {
      "@type": "PostalAddress",
      "addressLocality": "Dubai",
      "addressRegion": "Dubai",
      "addressCountry": "AE"
    },
    "geo": {
      "@type": "GeoCoordinates",
      "latitude": 25.2048,
      "longitude": 55.2708
    },
    "openingHoursSpecification": [
      {
        "@type": "OpeningHoursSpecification",
        "dayOfWeek": ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
        "opens": "08:00",
        "closes": "22:00"
      }
    ],
    "sameAs": [
      BRAND.instagram,
      BRAND.facebook,
      BRAND.tiktok
    ]
  };

  const breadcrumbList = {
    "@type": "BreadcrumbList",
    "@id": `${data.canonical}#breadcrumb`,
    "itemListElement": data.breadcrumbs.map((b, idx) => ({
      "@type": "ListItem",
      "position": idx + 1,
      "name": b.name,
      "item": b.item
    }))
  };

  const service = {
    "@type": "Service",
    "@id": `${data.canonical}#service`,
    "name": data.title,
    "serviceType": data.serviceType,
    "description": data.description,
    "provider": {
      "@id": `${BASE_URL}/#organization`
    },
    "areaServed": [
      { "@type": "City", "name": "Dubai" },
      { "@type": "City", "name": "Abu Dhabi" },
      { "@type": "City", "name": "Sharjah" },
      { "@type": "Country", "name": "United Arab Emirates" }
    ],
    "hasOfferCatalog": {
      "@type": "OfferCatalog",
      "name": `${data.serviceType} Offerings`,
      "itemListElement": data.pillars.map((p, idx) => ({
        "@type": "Offer",
        "itemOffered": {
          "@type": "Service",
          "name": p.title,
          "description": p.desc
        }
      }))
    }
  };

  const faqPage = {
    "@type": "FAQPage",
    "@id": `${data.canonical}#faq`,
    "mainEntity": data.faqs.map(faq => ({
      "@type": "Question",
      "name": faq.q,
      "acceptedAnswer": {
        "@type": "Answer",
        "text": faq.a
      }
    }))
  };

  return {
    "@context": "https://schema.org",
    "@graph": [
      organization,
      breadcrumbList,
      service,
      faqPage
    ]
  };
}
